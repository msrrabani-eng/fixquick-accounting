'use strict';
const assert=require('assert');
const C=require('../www/receipt-intelligence.js');
let n=0;
function check(title,fn){try{fn();n++;}catch(e){console.error('FAIL '+title+'\n'+e.stack);process.exitCode=1;}}
const sample='انتقال وجه موفق\nمبلغ: ۲۵۰,۰۰۰,۰۰۰ ریال\nکد رهگیری: ۱۲۳۴۵۶۷۸۹\nتاریخ: ۱۴۰۵/۰۸/۲۲\nساعت: ۱۱:۴۲:۰۸\nبانک مبدا: ملت\nبانک مقصد: ملی';
const r=C.analyzeBankReceipt(sample);
check('amount in rial',()=>assert.strictEqual(r.amountRial,250000000));
check('tracking Persian digits',()=>assert.strictEqual(r.trackingCode,'123456789'));
check('date normalized',()=>assert.strictEqual(r.date,'1405/08/22'));
check('time captured',()=>assert.strictEqual(r.time,'11:42:08'));
check('source bank',()=>assert.strictEqual(r.sourceBank,'ملت'));
check('destination bank',()=>assert.strictEqual(r.destinationBank,'ملی'));
check('toman converts to rial',()=>assert.strictEqual(C.analyzeBankReceipt('مبلغ: ۲۵,۰۰۰,۰۰۰ تومان').amountRial,250000000));
check('no guessed unit',()=>assert.strictEqual(C.analyzeBankReceipt('مبلغ 25000000').amountRial,null));
check('no guessed bank sides',()=>{const r=C.analyzeBankReceipt('بانک ملت');assert.strictEqual(r.sourceBank,null);assert.strictEqual(r.destinationBank,null)});
check('missing code warns',()=>assert.ok(C.analyzeBankReceipt('مبلغ 250000 ریال').warnings.some(x=>x.includes('رهگیری'))));
check('duplicate tracking code detected',()=>{const st={tx:[{id:1,amount:250000000,desc:'کد رهگیری 123456789',date:'2026-11-13'}]};assert.deepStrictEqual(C.analyzeBankReceipt(sample,st).duplicateCandidates.map(x=>x.id),[1]);});
check('other transaction is not a duplicate',()=>{const st={tx:[{id:1,desc:'کد رهگیری 999999999'}]};assert.strictEqual(C.analyzeBankReceipt(sample,st).duplicateCandidates.length,0);});
check('does not change accounting data',()=>{const st={tx:[{id:1,desc:'کد رهگیری 123456789'}]};const before=JSON.stringify(st);C.analyzeBankReceipt(sample,st);assert.strictEqual(JSON.stringify(st),before);});
check('never auto approves receipt',()=>{assert.strictEqual(r.reviewRequired,true);assert.strictEqual(r.verified,false)});
check('empty input',()=>assert.ok(C.analyzeBankReceipt('').warnings.length));
check('amount conflicts flagged',()=>assert.ok(C.analyzeBankReceipt('مبلغ 250000 ریال\nکارمزد 10000 ریال').warnings.some(x=>x.includes('چند مبلغ'))));
console.log(n+' vol005 bank receipt intelligence tests passed');
