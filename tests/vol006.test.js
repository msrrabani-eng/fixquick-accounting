'use strict';
const assert = require('assert');
const fs = require('fs');
const C = require('../www/receipt-intelligence.js');
const OCR = require('../www/receipt-ocr.js');
const pages = fs.readFileSync(require('path').join(__dirname, '../www/pages.js'), 'utf8');
const html = fs.readFileSync(require('path').join(__dirname, '../www/index.html'), 'utf8');
const workflow = fs.readFileSync(require('path').join(__dirname, '../.github/workflows/build-apk.yml'), 'utf8');
let passed=0;
function check(name, fn) { try { fn(); passed++; } catch(e) { console.error('FAILED:', name, e.message); process.exitCode=1; } }
check('camera capture available', () => assert.match(pages, /capture="environment"/));
check('gallery input separate from camera', () => assert.match(pages, /id="tf-gallery-file"[^>]*accept="image\/\*"/));
check('both person form types only', () => assert.match(pages, /isPay && !tx \?/));
check('image OCR called on photo', () => assert.match(pages, /ReceiptOCR\.recognize\(file/));
check('human confirmation to apply values', () => assert.match(pages, /tf-ocr-apply/));
check('OCR does not call addTx directly', () => assert.doesNotMatch(fs.readFileSync(require('path').join(__dirname, '../www/receipt-ocr.js'), 'utf8'), /addTx\(/));
check('registration calls existing accounting engine', () => assert.match(pages, /Core\.addTx\(S, \{ personId, type: t/));
check('duplicate check before registration', () => assert.match(pages, /duplicate\.length && !\(await confirmBox/));
check('tracking reference included', () => assert.match(pages, /receiptNote = verifiedReceipt/));
check('amount converted to configured unit', () => assert.match(pages, /Core\.fmtInput\(r\.amountRial\)/));
check('Persian data and worker packaged by build', () => assert.match(workflow, /bash tools\/prepare_ocr\.sh/));
check('signing key pulled from encrypted secret', () => assert.match(workflow, /secrets\.FIXQ_KEYSTORE_BASE64/));
check('versionCode supports upgrades', () => assert.match(workflow, /100000 \+ \$\{\{ github\.run_number \}\}/));
check('no secret keystore in upload', () => assert.match(fs.readFileSync(require('path').join(__dirname,'../.gitignore'),'utf8'), /\*\.keystore/));
check('OCR loaded in application', () => assert.match(html, /ocr\/tesseract\.min\.js/));
check('OCR library local, not CDN', () => assert.doesNotMatch(html, /https?:\/\//));
check('valid image passes type filter', () => OCR.validateFile({type:'image/png',size:24000}));
check('nonimage rejected', () => assert.throws(() => OCR.validateFile({type:'application/pdf',size:100}), /عکس/));
check('image over 24MB rejected', () => assert.throws(() => OCR.validateFile({type:'image/jpeg',size:OCR.MAX_IMAGE_BYTES+1}), /۲۴/));
check('receipt duplicate found based on saved description', () => {const r=C.analyzeBankReceipt('کد رهگیری 123456', {tx:[{id:22, desc:'رسید | کد رهگیری 123456'}]});assert.strictEqual(r.duplicateCandidates.length,1);});
console.log(passed+' v006 integration checks passed');
