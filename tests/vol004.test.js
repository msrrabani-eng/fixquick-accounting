'use strict';
const assert = require('assert');
const C = require('../www/smartsearch.js');
let count=0;
function check(name,fn){try{fn();count++;}catch(e){console.error('FAIL '+name+'\n'+e.stack);process.exitCode=1;}}
const P={id:1,name:'علی محمدی',phone:'09121234567',code:'C100'};
const Q={id:2,name:'مریم احمدی',phone:'09129876543'};
const st=C.emptyState();
st.people=[P,Q];
st.products=[{id:10,name:'iPhone 16 Pro Max',sku:'16PM',barcode:'1234567890',category:'آیفون'}];
st.accounts=[{id:10,name:'بانک ملت',kind:'bank',card:'6037999912345678'}];
st.cheques=[{id:21,cyc:true,state:'box',direction:'receive',amount:2500000000,serial:'012345678901',bank:'ملت',personId:1,dueDate:'2026-12-01',date:'2026-11-01',note:'واریز ضمانت'},{id:22,cyc:true,state:'spent',direction:'receive',amount:3000000000,serial:'998811223344',bank:'ملی',personId:2,dueDate:'2026-12-12',date:'2026-11-02'}];
st.expenses=[{id:30,title:'اجاره دفتر',category:'اجاره',amount:1000000000,date:'2026-11-03'},{id:31,title:'قبض برق',category:'قبض',amount:5000000,date:'2026-11-05'}];
st.tx=[{id:40,type:'receipt',amount:1000000000,personId:1,date:'2026-11-04',desc:'واریز کارت به کارت'}];
st.invoices=[{id:50,no:'140',type:'sale',personId:1,date:'2026-11-05',discount:0,vatRate:0,items:[{productId:10,qty:1,price:2500000000,note:'نمونه'}]}];
check('parse Persian and English digits and Toman scale',()=>{const r=C.smartParseSearch('چک ۲۵۰ میلیون تومان');assert.strictEqual(r.amount,2500000000);assert.strictEqual(r.mode,'cheques');});
check('search check by person typo',()=>{const r=C.smartFind(st,'چک علی');assert.deepStrictEqual(r.cheques.map(x=>x.id),[21]);});
check('find cheque by serial tail, Persian numerals',()=>{const r=C.smartFind(st,'چک ۸۹۰۱');assert.deepStrictEqual(r.cheques.map(x=>x.id),[21]);});
check('find cheque by money (Toman)',()=>{const r=C.smartFind(st,'چک ۲۵۰ میلیون تومان');assert.deepStrictEqual(r.cheques.map(x=>x.id),[21]);});
check('cheque state filter from everyday language',()=>{const r=C.smartFind(st,'چک خرج شده');assert.deepStrictEqual(r.cheques.map(x=>x.id),[22]);});
check('date search Jalali matches due date',()=>{const q='چک '+C.isoToJalali('2026-12-01');assert.deepStrictEqual(C.smartFind(st,q).cheques.map(x=>x.id),[21]);});
check('fuzzy bank search Arabic variants',()=>{const r=C.smartFind(st,'چک بانك ملت');assert.deepStrictEqual(r.cheques.map(x=>x.id),[21]);});
check('invoice full amount can be found',()=>{const r=C.smartFind(st,'فاکتور ۲۵۰ میلیون تومان');assert.deepStrictEqual(r.invoices.map(x=>x.id),[50]);});
check('expenses query by title',()=>{const r=C.smartFind(st,'هزینه اجاره');assert.deepStrictEqual(r.expenses.map(x=>x.id),[30]);});
check('search bank by card partial',()=>{const r=C.smartFind(st,'بانک ۵۶۷۸');assert.deepStrictEqual(r.accounts.map(x=>x.id),[10]);});
check('receipt search by person',()=>{const r=C.smartFind(st,'دریافت علی');assert.deepStrictEqual(r.tx.map(x=>x.id),[40]);});
check('cheque search is read only',()=>{const before=JSON.stringify(st);C.smartFind(st,'چک علی');assert.strictEqual(JSON.stringify(st),before);});
check('local cheque filter matches amount and rejects other amount',()=>{assert.ok(C.smartChequeMatch(st.cheques[0],'۲۵۰ میلیون تومان','علی محمدی'));assert.ok(!C.smartChequeMatch(st.cheques[0],'۳۰۰ میلیون تومان','علی محمدی'));});
check('local expense filter amounts and text',()=>{assert.ok(C.smartExpenseMatch(st.expenses[0],'اجاره'));assert.ok(!C.smartExpenseMatch(st.expenses[1],'اجاره'));});
check('empty query returns no global records',()=>{assert.ok(!C.smartFind(st,'').cheques.length);});
check('search matches iPhone and Persian/English aliases',()=>{assert.deepStrictEqual(C.smartFind(st,'آیفون ۱۶ پرو مکس').products.map(x=>x.id),[10]);});
check('performance on large archive capped',()=>{const x=C.emptyState();x.people=st.people;x.cheques=Array.from({length:10000},(_,i)=>({...st.cheques[0],id:i,serial:String(i).padStart(12,'0')}));const start=Date.now(),r=C.smartFind(x,'چک علی',{limit:15});assert.strictEqual(r.cheques.length,15);assert.ok(Date.now()-start<3500);});
// Serial/IMEI lookup regression tests: all are read-only and use synthetic invoices.
const se=C.emptyState();
const customer=C.addPerson(se,{name:'تأمین کننده'}).person;
const phone=C.addProduct(se,{name:'iPhone 16 Pro Max',category:'گوشی',serialReq:true}).product;
const second=C.addProduct(se,{name:'iPhone 17 Pro',category:'گوشی',serialReq:true}).product;
const firstImei='490154203237518';
const secondImei='355031234567890';
assert.ok(C.addInvoice(se,{type:'purchase',personId:customer.id,date:'2026-11-10',items:[{productId:phone.id,qty:1,price:1000,note:firstImei}]}).ok);
assert.ok(C.addInvoice(se,{type:'purchase',personId:customer.id,date:'2026-11-11',items:[{productId:second.id,qty:1,price:2000,note:secondImei}]}).ok);
const expectSerial=(q, serial=firstImei)=>assert.ok(C.serialHistory(se,q).some(x=>x.serial===serial),q);
check('IMEI prefix 3 digits',()=>expectSerial('490'));
check('IMEI prefix 4 digits',()=>expectSerial('4901'));
check('IMEI prefix Persian digits',()=>expectSerial('۴۹۰۱'));
check('IMEI with label',()=>expectSerial('IMEI: ۴۹۰'));
check('IMEI suffix 4 digits preserved',()=>expectSerial('7518'));
check('IMEI middle 6 digits preserved',()=>expectSerial('420323'));
check('IMEI exact match preserved',()=>expectSerial(firstImei));
check('different IMEI prefix targets different product',()=>expectSerial('355',secondImei));
check('two digits are too ambiguous',()=>assert.deepStrictEqual(C.serialHistory(se,'49'),[]));
check('short middle fragments do not produce false positive',()=>assert.deepStrictEqual(C.serialHistory(se,'2032'),[]));
check('serial product id lookup',()=>assert.deepStrictEqual([...C.serialProductIds(se,'۴۹۰۱')],[phone.id]));
check('global search Persian IMEI prefix',()=>assert.ok(C.search(se,'۴۹۰').serials.some(x=>x.serial===firstImei)));
check('global search phrase IMEI prefix',()=>assert.ok(C.search(se,'IMEI 490').serials.some(x=>x.serial===firstImei)));
check('global search prefix no mutation',()=>{const before=JSON.stringify(se); C.search(se,'۴۹۰');C.serialHistory(se,'490');assert.strictEqual(JSON.stringify(se),before)});
check('invoice quick-filter prefix 3 digits',()=>assert.ok(C.docMatch(C.invText(se,se.invoices[0]),C.docQuery('۴۹۰'))));
check('invoice quick-filter excludes unrelated IMEI',()=>assert.ok(!C.docMatch(C.invText(se,se.invoices[0]),C.docQuery('۳۵۵'))));
check('prefix performance with many invoices',()=>{const t0=Date.now();for(let i=0;i<200;i++){C.serialHistory(se,'490');}assert.ok(Date.now()-t0<2000);});
check('smartFind invoice by IMEI prefix',()=>assert.deepStrictEqual(C.smartFind(se,'IMEI 490').invoices.map(i=>i.id),[se.invoices[0].id]));
check('smartInvoiceMatch prefix',()=>assert.ok(C.smartInvoiceMatch(se,se.invoices[0],'سریال ۴۹۰')));
check('smartInvoiceMatch excludes other prefix',()=>assert.ok(!C.smartInvoiceMatch(se,se.invoices[0],'سریال ۳۵۵')));

check('sold IMEI remains discoverable by prefix',()=>{
  const buyer=C.addPerson(se,{name:'خریدار'}).person;
  const sale=C.addInvoice(se,{type:'sale',personId:buyer.id,date:'2026-11-12',items:[{productId:phone.id,qty:1,price:2000,note:firstImei}]});
  assert.ok(sale.ok,sale.error);
  const r=C.serialHistory(se,'۴۹۰');
  assert.ok(r.some(x=>x.serial===firstImei && !x.inStock && x.state==='فروخته شده'));
});
check('sold IMEI still maps to linked product and invoice',()=>{
  assert.ok(C.serialProductIds(se,'490').has(phone.id));
  assert.ok(C.search(se,'IMEI 490').serials.some(x=>x.serial===firstImei));
  assert.ok(C.smartFind(se,'IMEI 490').invoices.some(x=>x.type==='sale'));
});
console.log(count+' vol004 regression tests passed (including IMEI prefix)');
